  // Trace (sans dessiner) le contour de tête choisi
  headPath(ctx, id, x, y, r = 12) {
    ctx.beginPath();
    if (id === 'head_square') ctx.roundRect(x - r, y - r, r * 2, r * 2, 4);
    else if (id === 'head_tv') {
      ctx.roundRect(x - r - 2, y - r + 1, r * 2 + 4, r * 2 - 3, 5);
      ctx.moveTo(x - 4, y - r + 1); ctx.lineTo(x - 9, y - r - 8);
      ctx.moveTo(x + 4, y - r + 1); ctx.lineTo(x + 9, y - r - 8);
    } else if (id === 'head_diamond') {
      ctx.moveTo(x, y - r - 3); ctx.lineTo(x + r + 2, y); ctx.lineTo(x, y + r + 3); ctx.lineTo(x - r - 2, y); ctx.closePath();
    } else if (id === 'head_hex') {
      for (let i = 0; i < 6; i++) { const a = Math.PI / 6 + i * Math.PI / 3; ctx[i ? 'lineTo' : 'moveTo'](x + Math.cos(a) * (r + 1), y + Math.sin(a) * (r + 1)); }
      ctx.closePath();
    } else ctx.arc(x, y, r, 0, Math.PI * 2);
  },

